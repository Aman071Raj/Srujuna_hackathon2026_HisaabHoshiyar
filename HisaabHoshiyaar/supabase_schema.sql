-- 1. Create Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    biz_name TEXT NOT NULL,
    biz_type TEXT DEFAULT '',
    biz_size TEXT DEFAULT '',
    country TEXT DEFAULT 'INR',
    currency TEXT DEFAULT 'INR',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Customers Table
CREATE TABLE IF NOT EXISTS public.customers (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    history JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Transactions Table
CREATE TABLE IF NOT EXISTS public.transactions (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    cust TEXT REFERENCES public.customers(id) ON DELETE SET NULL,
    type TEXT NOT NULL CHECK (type IN ('customer', 'supplier', 'expense', 'payroll', 'loan', 'cust', 'sup', 'pay', 'exp')),
    dir TEXT NOT NULL CHECK (dir IN ('in', 'out')),
    amount BIGINT NOT NULL,
    day INTEGER DEFAULT 0,
    delay INTEGER DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'expected' CHECK (status IN ('expected', 'settled', 'overdue')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Comms / Payment Reminders Table
CREATE TABLE IF NOT EXISTS public.comms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts BIGINT NOT NULL,
    cust TEXT,
    ch TEXT NOT NULL, -- 'Email' or 'SMS'
    msg TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Indexes for fast cash-flow aggregations and queries
CREATE INDEX IF NOT EXISTS idx_transactions_cust ON public.transactions(cust);
CREATE INDEX IF NOT EXISTS idx_transactions_status ON public.transactions(status);
CREATE INDEX IF NOT EXISTS idx_transactions_day ON public.transactions(day);
CREATE INDEX IF NOT EXISTS idx_comms_ts ON public.comms(ts DESC);

-- 5. Row Level Security (RLS) Setup
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comms ENABLE ROW LEVEL SECURITY;

